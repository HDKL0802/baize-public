// BuiltinNames 有内置模板的文件名（排序后），用于错误提示与界面提示
func BuiltinNames() []string {
	names := make([]string, 0, len(Templates))
	for name := range Templates {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}